interface BrandIconProps {
  name: BrandName;
  /** Андоза дар px (пешфарз 44 — ҳадафи ламс барои тугмаҳо) */
  size?: number;
  className?: string;
}

export default function BrandIcon({
  name,
  size = 44,
  className = "",
}: BrandIconProps) {
  // useId → ":r1:" — ишораҳои `url(#…)` дар SVG аз он мушкил мегирифтанд
  const uid = useId().replace(/:/g, "");

  const base: SVGProps<SVGSVGElement> = {
    width: size,
    height: size,
    viewBox: "0 0 24 24",
    "aria-hidden": true,
    focusable: "false",
    preserveAspectRatio: "xMidYMid meet",
    shapeRendering: "geometricPrecision",
    className,
  };

  if (name === "telegram") {
    // 🔵 Доираи пурра, градиенти уфуқӣ + ҳавопаймои сафеди пур
    const grad = `tg-grad-${uid}`;
    return (
      <svg {...base}>
        <defs>
          <linearGradient id={grad} x1="0" y1="0" x2="1" y2="0">
            <stop offset="0" stopColor="#2AABEE" />
            <stop offset="1" stopColor="#229ED9" />
          </linearGradient>
        </defs>
        <path d={TELEGRAM_CIRCLE} fill={`url(#${grad})`} />
        <path d={TELEGRAM_PLANE} fill="#FFFFFF" />
      </svg>
    );
  }

  if (name === "whatsapp") {
    // 💚 Пуфаки сухани расмӣ (#25D366) + телефони сафед дар дохил
    return (
      <svg {...base}>
        <path d={WHATSAPP_BUBBLE} fill="#25D366" />
        <path d={WHATSAPP_PHONE} fill="#FFFFFF" />
      </svg>
    );
  }

  // 🟪 Чоркунҷаи гирди радиуси ~28% + градиенти радиалӣ аз поёни чап + камераи сафед
  const grad = `ig-grad-${uid}`;
  return (
    <svg {...base}>
      <defs>
        <radialGradient id={grad} cx="0%" cy="100%" r="140%">
          <stop offset="0" stopColor="#FEDA75" />
          <stop offset="0.25" stopColor="#FA7E1E" />
          <stop offset="0.5" stopColor="#D62976" />
          <stop offset="0.75" stopColor="#962FBF" />
          <stop offset="1" stopColor="#4F5BD5" />
        </radialGradient>
      </defs>
      <rect x="0" y="0" width="24" height="24" rx="6.72" fill={`url(#${grad})`} />
      {/* Камера каме дар дохил (ҳудуд ~10%) — мисли логои расмӣ */}
      <g transform="translate(12 12) scale(0.8) translate(-12 -12)">
        <path d={INSTAGRAM_CAMERA} fill="#FFFFFF" />
      </g>
    </svg>
  );
}
